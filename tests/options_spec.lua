-- The options: a page in Settings > AddOns and its own window, and the slash command's list.

describe("the options", function()
    it("are a page named after the addon", function()
        local c = NewClient():login()
        assert.are.same({ c.Addon.NAME }, c.pageNames)
    end)

    it("switch the tooltip line and open the list", function()
        local c = NewClient():login()
        local options = c.Addon:OptionsTable()
        local tooltip = options.args.tooltip
        assert.is_true(tooltip.get())
        tooltip.set(nil, false)
        assert.is_false(c.Addon.db.profile.tooltip)
        options.args.open.func()
        assert.is_true(c.Addon.window.frame:IsShown())
    end)

    it("open in their own window with the options or config command", function()
        local c = NewClient():login()
        c:slash("options")
        local dialog = LibStub("AceConfigDialog-3.0")
        assert.is_table(dialog.OpenFrames[c.Addon.NAME])
        dialog:Close(c.Addon.NAME)
        c:nextFrame()
        c:slash("config")
        assert.is_table(dialog.OpenFrames[c.Addon.NAME])
    end)

    it("are listed by an unknown command", function()
        local c = NewClient():login()
        c:slash("what")
        assert.is_true(c:printedContains("/seek toggle - show or hide the list"))
        assert.is_true(c:printedContains("/seek options - open the options"))
        c:slash("toggle")
        assert.is_true(c.Addon.window.frame:IsShown())
    end)
end)
